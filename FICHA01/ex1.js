// ------------------------------------------------------
// 1. Declaração e inicialização de variáveis
// ------------------------------------------------------

// a) Variável para armazenar o primeiro nome da pessoa
let firstName = "Ricardo";

// b) Variável para armazenar a idade
let age = 51;

// c) Variável para armazenar a cidade onde vive
let city = "Porto";

// d) Variável para indicar se é de nacionalidade portuguesa
// true significa verdadeiro; false significa falso
let isPortuguese = true;


// ------------------------------------------------------
// 2. Atualizar o primeiro nome
// ------------------------------------------------------

// Podemos alterar o valor de uma variável declarada com let.
// Neste caso, juntamos o primeiro e o último nome.
firstName = "Ricardo Queirós";


// ------------------------------------------------------
// 3. Criar a variável doubleAge
// ------------------------------------------------------

// O operador * permite fazer uma multiplicação.
// Aqui calculamos o dobro da idade.
let doubleAge = age * 2;


// ------------------------------------------------------
// 4. Criar uma variável para o país
// ------------------------------------------------------

let country = "Portugal";


// ------------------------------------------------------
// 5. Criar a variável myLocation
// ------------------------------------------------------

// O operador + permite concatenar (juntar) strings.
// Queremos obter, por exemplo:
// "Porto, Portugal"
let myLocation = city + ", " + country;


// ------------------------------------------------------
// 6. Operações matemáticas
// ------------------------------------------------------

// Números fornecidos no enunciado
let numero1 = 10;
let numero2 = 3;


// Soma
let soma = numero1 + numero2;

// Subtração
let subtracao = numero1 - numero2;

// Multiplicação
let multiplicacao = numero1 * numero2;

// Divisão
let divisao = numero1 / numero2;

// Resto da divisão (módulo)
// O operador % devolve o resto da divisão.
let modulo = numero1 % numero2;