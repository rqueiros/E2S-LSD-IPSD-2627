// Prioridade numa urgência
let prioridade = 3;

if (prioridade === 1) {
    console.log("Emergência");
} else if (prioridade === 2) {
    console.log("Muito urgente");
} else if (prioridade === 3) {
    console.log("Urgente");
} else if (prioridade === 4) {
    console.log("Pouco urgente");
} else if (prioridade === 5) {
    console.log("Não urgente");
} else {
    console.log("Prioridade inválida");
}
